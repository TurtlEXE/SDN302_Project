import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import {
  VNPayClient,
  formatDateToVnpay,
  parseVnpayDate,
  secureCompare,
} from '../../src/integrations/vnpay.client.js';

describe('VNPay Client Unit Tests', () => {
  const client = new VNPayClient({
    tmnCode: 'TEST_TMN',
    hashSecret: 'MY_SECRET_KEY_1234567890',
    vnpUrl: 'https://sandbox.vnpayment.vn/paymentv2/vpcpay.html',
    returnUrl: 'http://localhost:3000/payments/vnpay-return',
  });

  describe('formatDateToVnpay and parseVnpayDate', () => {
    it('should format date to YYYYMMDDHHmmss in GMT+7 correctly', () => {
      // Create a known UTC date: 2026-10-29T10:30:00Z -> In GMT+7 it is 17:30:00
      const utcDate = new Date(Date.UTC(2026, 9, 29, 10, 30, 0));
      const formatted = formatDateToVnpay(utcDate);
      assert.equal(formatted, '20261029173000');
    });

    it('should parse YYYYMMDDHHmmss in GMT+7 back to matching UTC Date', () => {
      const vnpDateStr = '20261029173000';
      const parsedDate = parseVnpayDate(vnpDateStr);
      assert.ok(parsedDate instanceof Date);
      assert.equal(parsedDate.toISOString(), '2026-10-29T10:30:00.000Z');
    });

    it('should return null for invalid date string format', () => {
      assert.equal(parseVnpayDate(''), null);
      assert.equal(parseVnpayDate('invalid'), null);
      assert.equal(parseVnpayDate('20261029'), null);
      assert.equal(parseVnpayDate(null), null);
    });
  });

  describe('secureCompare', () => {
    it('should return true for identical strings (case-insensitive)', () => {
      assert.equal(secureCompare('abcdef', 'abcdef'), true);
      assert.equal(secureCompare('ABCDEF', 'abcdef'), true);
    });

    it('should return false for different strings', () => {
      assert.equal(secureCompare('abcdef', '123456'), false);
      assert.equal(secureCompare('short', 'longer_string'), false);
      assert.equal(secureCompare(null, 'test'), false);
    });
  });

  describe('createPaymentUrl and verifySignature', () => {
    it('should generate valid payment URL with sorted params and correct amount multiplication (x100)', () => {
      const createDate = new Date(Date.UTC(2026, 9, 29, 10, 0, 0));
      const expireDate = new Date(Date.UTC(2026, 9, 29, 10, 10, 0)); // 10 minutes hold
      const amountVnd = 180000;

      const paymentUrl = client.createPaymentUrl({
        txnRef: 'PO2026102901',
        amountVnd,
        orderInfo: 'Thanh toan don BR01',
        ipAddr: '192.168.1.1',
        createDate,
        expireDate,
      });

      assert.ok(paymentUrl.startsWith('https://sandbox.vnpayment.vn/paymentv2/vpcpay.html?'));
      const url = new URL(paymentUrl);

      // Amount must be multiplied by 100 (Criterion 44: 180,000 VND -> 18,000,000)
      assert.equal(url.searchParams.get('vnp_Amount'), '18000000');
      assert.equal(url.searchParams.get('vnp_TxnRef'), 'PO2026102901');
      assert.equal(url.searchParams.get('vnp_TmnCode'), 'TEST_TMN');
      assert.equal(url.searchParams.get('vnp_CurrCode'), 'VND');
      assert.equal(url.searchParams.get('vnp_Version'), '2.1.0');
      assert.equal(url.searchParams.get('vnp_Command'), 'pay');
      assert.equal(url.searchParams.get('vnp_IpAddr'), '192.168.1.1');
      assert.equal(url.searchParams.get('vnp_ExpireDate'), '20261029171000'); // Criterion 46

      const secureHash = url.searchParams.get('vnp_SecureHash');
      assert.ok(secureHash && secureHash.length === 128); // SHA-512 hex is 128 chars
    });

    it('should verify valid signature generated by the client', () => {
      const createDate = new Date(Date.UTC(2026, 9, 29, 10, 0, 0));
      const expireDate = new Date(Date.UTC(2026, 9, 29, 10, 10, 0));

      const paymentUrl = client.createPaymentUrl({
        txnRef: 'PO99988877',
        amountVnd: 250000,
        orderInfo: 'Order 999',
        expireDate,
        createDate,
      });

      const url = new URL(paymentUrl);
      const queryParams = Object.fromEntries(url.searchParams.entries());

      const isValid = client.verifySignature(queryParams);
      assert.equal(isValid, true);
    });

    it('should reject tampered query parameters', () => {
      const createDate = new Date(Date.UTC(2026, 9, 29, 10, 0, 0));
      const expireDate = new Date(Date.UTC(2026, 9, 29, 10, 10, 0));

      const paymentUrl = client.createPaymentUrl({
        txnRef: 'PO99988877',
        amountVnd: 250000,
        orderInfo: 'Order 999',
        expireDate,
        createDate,
      });

      const url = new URL(paymentUrl);
      const queryParams = Object.fromEntries(url.searchParams.entries());

      // Tamper amount
      queryParams.vnp_Amount = '50000000';
      assert.equal(client.verifySignature(queryParams), false);

      // Tamper secure hash
      queryParams.vnp_SecureHash = 'bad_hash';
      assert.equal(client.verifySignature(queryParams), false);

      // Missing secure hash
      delete queryParams.vnp_SecureHash;
      assert.equal(client.verifySignature(queryParams), false);
    });
  });
});

